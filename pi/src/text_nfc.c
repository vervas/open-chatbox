#define N_PAIRS (sizeof(k_pairs) / sizeof(k_pairs[0]))

static uint32_t compose(uint32_t base, uint32_t mark)
{
    size_t lo = 0, hi = N_PAIRS;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        const nfc_pair_t *p = &k_pairs[mid];
        if (p->base == base && p->mark == mark)
            return p->composed;
        if (p->base < base || (p->base == base && p->mark < mark))
            lo = mid + 1;
        else
            hi = mid;
    }
    return 0;
}

/* Decode one UTF-8 sequence at s. Returns its length (0 at the end), with
 * *cp = 0xFFFFFFFF for a malformed byte (passed through as is). */
static size_t decode(const unsigned char *s, uint32_t *cp)
{
    if (!s[0]) return 0;
    if (s[0] < 0x80) { *cp = s[0]; return 1; }
    size_t n = s[0] >= 0xF0 ? 4 : s[0] >= 0xE0 ? 3 : s[0] >= 0xC0 ? 2 : 0;
    if (n == 0) { *cp = 0xFFFFFFFFu; return 1; }
    uint32_t v = s[0] & (0x3F >> (n - 1));
    for (size_t i = 1; i < n; i++) {
        if ((s[i] & 0xC0) != 0x80) { *cp = 0xFFFFFFFFu; return 1; }
        v = (v << 6) | (s[i] & 0x3F);
    }
    *cp = v;
    return n;
}

static size_t encode(uint32_t c, unsigned char *out)
{
    if (c < 0x80) { out[0] = (unsigned char)c; return 1; }
    out[0] = (unsigned char)(0xC0 | (c >> 6));
    out[1] = (unsigned char)(0x80 | (c & 0x3F));
    return 2;           /* compositions here are all below U+0800 */
}

void text_utf8_nfc(char *str)
{
    unsigned char *s = (unsigned char *)str, *w = s;
    unsigned char *last = NULL;     /* start of the last written character */
    uint32_t last_cp = 0;
    uint32_t cp;
    size_t n;
    while ((n = decode(s, &cp)) > 0) {
        if (cp >= 0x300 && cp < 0x370) {
            uint32_t c = last ? compose(last_cp, cp) : 0;
            if (c) {
                w = last + encode(c, last);
                last_cp = c;
            }
            /* else dropped: LVGL cannot stack marks and the fonts have none */
            s += n;
            continue;
        }
        last = w;
        last_cp = cp == 0xFFFFFFFFu ? 0 : cp;
        for (size_t i = 0; i < n; i++)
            *w++ = *s++;
    }
    *w = '\0';
}
